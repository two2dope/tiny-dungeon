export function normalizeMapId(mapId?: number): number {
  if (typeof mapId !== 'number' || !Number.isFinite(mapId)) return 1;
  const rounded = Math.trunc(mapId);
  if (rounded < 1) return 1;
  if (rounded > 7) return 7;
  return rounded;
}

